// ---------------------------------------------------------------------------
// Nearby computation — all 5 tabs (Transit, Schools, Parks, Museums, Everyday)
// Data files in data/ (generated by scripts/fetch-area-data.mjs)
// Distances are straight-line miles (2 decimals). Subway filtered to 1 mile.
// ---------------------------------------------------------------------------

let _subwayData = null
let _busGrid = null
let _schoolsData = null
let _parksData = null
let _museumsData = null
let _everydayData = null

function loadSubway() {
  if (!_subwayData) {
    try { _subwayData = _require('./data/subway-compact.json') } catch { _subwayData = [] }
  }
  return _subwayData
}
function loadBusGrid() {
  if (!_busGrid) {
    try { _busGrid = _require('./data/bus-compact.json') } catch { _busGrid = {} }
  }
  return _busGrid
}
function loadSchools() {
  if (!_schoolsData) {
    try { _schoolsData = _require('./data/schools-compact.json') } catch { _schoolsData = [] }
  }
  return _schoolsData
}
function loadParks() {
  if (!_parksData) {
    try { _parksData = _require('./data/parks-compact.json') } catch { _parksData = [] }
  }
  return _parksData
}
function loadMuseums() {
  if (!_museumsData) {
    try { _museumsData = _require('./data/museums-compact.json') } catch { _museumsData = [] }
  }
  return _museumsData
}
function loadEveryday() {
  if (!_everydayData) {
    try { _everydayData = _require('./data/everyday-compact.json') } catch { _everydayData = [] }
  }
  return _everydayData
}

function distMetres(lat1, lng1, lat2, lng2) {
  const R = 6_371_000
  const toRad = d => (d * Math.PI) / 180
  const dLat = toRad(lat2 - lat1)
  const dLng = toRad(lng2 - lng1)
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(a))
}

function toMiles(metres) {
  return Math.round((metres / 1609.344) * 100) / 100
}

function nearest5(items, lat, lng, maxMiles = 999) {
  return items
    .map(item => ({ ...item, _d: distMetres(lat, lng, item.lat, item.lng) }))
    .filter(item => toMiles(item._d) <= maxMiles)
    .sort((a, b) => a._d - b._d)
    .slice(0, 5)
}

/** Compute NearbyData for a building at (lat, lng). Returns null if no coords. */
function computeNearby(lat, lng) {
  if (!lat || !lng) return null

  // --- Transit: subway (up to 5 within 1 mile), bus (up to 5) ---
  const subway = loadSubway()
  const busGrid = loadBusGrid()

  const subwayWithDist = subway
    .map(s => ({ ...s, d: distMetres(lat, lng, s.lat, s.lng) }))
    .filter(s => toMiles(s.d) <= 1)
    .sort((a, b) => a.d - b.d)
  const nearestSubway = subwayWithDist.slice(0, 5).map(s => ({
    name: s.n,
    routes: s.r.map((id, i) => ({ id, color: s.c[i] ?? '#888888' })),
    miles: toMiles(s.d),
  }))

  const cellLat = Math.floor(lat * 100)
  const cellLng = Math.floor(lng * 100)
  const nearbyBusAll = []
  for (let dLat = -1; dLat <= 1; dLat++) {
    for (let dLng = -1; dLng <= 1; dLng++) {
      const cell = `${cellLat + dLat},${cellLng + dLng}`
      for (const stop of busGrid[cell] ?? []) {
        nearbyBusAll.push({ ...stop, d: distMetres(lat, lng, stop.lat, stop.lng) })
      }
    }
  }
  nearbyBusAll.sort((a, b) => a.d - b.d)
  const seenRouteKeys = new Set()
  const nearestBus = []
  for (const stop of nearbyBusAll) {
    const key = stop.r.slice().sort().join(',')
    if (seenRouteKeys.has(key)) continue
    seenRouteKeys.add(key)
    nearestBus.push({ name: stop.n, routes: stop.r, miles: toMiles(stop.d) })
    if (nearestBus.length >= 5) break
  }

  // --- Schools (top 5) ---
  const schools = nearest5(loadSchools(), lat, lng).map(s => ({
    name: s.n, level: s.level, miles: toMiles(s._d), lat: s.lat, lng: s.lng,
  }))

  // --- Parks (top 5) ---
  const parks = nearest5(loadParks(), lat, lng).map(p => ({
    name: p.n, miles: toMiles(p._d), lat: p.lat, lng: p.lng,
  }))

  // --- Museums (top 5) ---
  const museums = nearest5(loadMuseums(), lat, lng).map(m => ({
    name: m.n, miles: toMiles(m._d), lat: m.lat, lng: m.lng,
  }))

  // --- Everyday: libraries + hospitals (top 5 total, closest first) ---
  const everyday = nearest5(loadEveryday(), lat, lng).map(e => ({
    name: e.n, kind: e.kind, miles: toMiles(e._d), lat: e.lat, lng: e.lng,
  }))

  return { subway: nearestSubway, bus: nearestBus, schools, parks, museums, everyday }
}

// ---------------------------------------------------------------------------
// Geocoding — NYC GeoSearch (Pelias, planninglabs.nyc)
// Called only when HC provides no lat/lng for a building.
// Accepts confident matches in the same borough; rejects "fallback" matches.
// ---------------------------------------------------------------------------

const GEOSEARCH_URL = 'https://geosearch.planninglabs.nyc/v2/search'

/** Map HC borough codes / names → GeoSearch borough names. */
const BOROUGH_MAP = {
  MN: 'Manhattan', BK: 'Brooklyn', QN: 'Queens', BX: 'Bronx', SI: 'Staten Island',
  MANHATTAN: 'Manhattan', BROOKLYN: 'Brooklyn', QUEENS: 'Queens', BRONX: 'Bronx',
  'STATEN ISLAND': 'Staten Island',
}

/**
 * Geocode a building address using NYC GeoSearch.
 * Returns {lat, lng} only when the result is a confident match in the same
 * borough. Returns null on network error, no results, or borough mismatch.
 */
async function geocodeAddress(address, city, borough) {
  try {
    const query = [address, city, 'NY'].filter(Boolean).join(', ')
    const url = `${GEOSEARCH_URL}?text=${encodeURIComponent(query)}&size=1`
    const res = await fetch(url, {
      headers: { 'User-Agent': UA },
      signal: AbortSignal.timeout(5000),
    })
    if (!res.ok) return null
    const data = await res.json()

    const feature = data.features?.[0]
    if (!feature) return null

    const [lng, lat] = feature.geometry?.coordinates ?? []
    if (typeof lat !== 'number' || typeof lng !== 'number') return null

    // NYC bounding box sanity check
    if (lat < 40.4 || lat > 40.95 || lng < -74.3 || lng > -73.65) return null

    // Reject "fallback" matches — too coarse
    if (feature.properties?.match_type === 'fallback') return null

    // Borough check: must match the listing's borough (when known)
    const expectedBorough = BOROUGH_MAP[borough?.toUpperCase?.() ?? ''] ?? null
    if (expectedBorough) {
      const featureBorough = feature.properties?.borough
      if (featureBorough && featureBorough.toLowerCase() !== expectedBorough.toLowerCase()) return null
    }

    return { lat, lng }
  } catch {
    return null
  }
}

