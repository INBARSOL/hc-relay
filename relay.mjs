#!/usr/bin/env node
/**
 * Lotto Lane relay — GitHub Actions runner fetches Housing Connect data
 * (Azure IPs are not blocked by HC's WAF) and POSTs to the Worker one
 * listing at a time to stay under the Worker's 50 D1 subrequest limit.
 *
 * Also computes Nearby transit/parks for each listing here (GitHub Actions has
 * no CPU time limit) so the Worker only validates and stores it.
 *
 * Usage:
 *   node relay.mjs
 *
 * Required environment variables (set as GitHub encrypted secrets):
 *   WORKER_URL   — https://lotto-lane-api.nyc-housing-app.workers.dev
 *   API_SECRET   — same value as the Worker's API_SECRET secret
 *
 * Optional:
 *   DRY_RUN=1    — fetch HC data but skip all Worker POSTs (for local testing)
 */
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const _require = createRequire(import.meta.url)

const WORKER_URL = process.env.WORKER_URL?.trim()
const API_SECRET = process.env.API_SECRET?.trim()
const DRY_RUN = process.env.DRY_RUN === '1'

// ---------------------------------------------------------------------------
// Nearby computation — all 5 tabs (Transit, Schools, Parks, Museums, Everyday)
// Data files in data/ (generated by scripts/fetch-area-data.mjs)
// Distances are straight-line miles (2 decimals). Subway filtered to 1 mile.
// ---------------------------------------------------------------------------

let _subwayData = null
let _busGrid = null
let _schoolsData = null
let _parksData = null
let _museumsData = null
let _everydayData = null

function loadSubway() {
  if (!_subwayData) {
    try { _subwayData = _require('./data/subway-compact.json') } catch { _subwayData = [] }
  }
  return _subwayData
}
function loadBusGrid() {
  if (!_busGrid) {
    try { _busGrid = _require('./data/bus-compact.json') } catch { _busGrid = {} }
  }
  return _busGrid
}
function loadSchools() {
  if (!_schoolsData) {
    try { _schoolsData = _require('./data/schools-compact.json') } catch { _schoolsData = [] }
  }
  return _schoolsData
}
function loadParks() {
  if (!_parksData) {
    try { _parksData = _require('./data/parks-compact.json') } catch { _parksData = [] }
  }
  return _parksData
}
function loadMuseums() {
  if (!_museumsData) {
    try { _museumsData = _require('./data/museums-compact.json') } catch { _museumsData = [] }
  }
  return _museumsData
}
function loadEveryday() {
  if (!_everydayData) {
    try { _everydayData = _require('./data/everyday-compact.json') } catch { _everydayData = [] }
  }
  return _everydayData
}

function distMetres(lat1, lng1, lat2, lng2) {
  const R = 6_371_000
  const toRad = d => (d * Math.PI) / 180
  const dLat = toRad(lat2 - lat1)
  const dLng = toRad(lng2 - lng1)
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(a))
}

function toMiles(metres) {
  return Math.round((metres / 1609.344) * 100) / 100
}

function nearest5(items, lat, lng, maxMiles = 999) {
  return items
    .map(item => ({ ...item, _d: distMetres(lat, lng, item.lat, item.lng) }))
    .filter(item => toMiles(item._d) <= maxMiles)
    .sort((a, b) => a._d - b._d)
    .slice(0, 5)
}

/** Compute NearbyData for a building at (lat, lng). Returns null if no coords. */
function computeNearby(lat, lng) {
  if (!lat || !lng) return null

  // --- Transit: subway (up to 5 within 1 mile), bus (up to 5) ---
  const subway = loadSubway()
  const busGrid = loadBusGrid()

  const subwayWithDist = subway
    .map(s => ({ ...s, d: distMetres(lat, lng, s.lat, s.lng) }))
    .filter(s => toMiles(s.d) <= 1)
    .sort((a, b) => a.d - b.d)
  const nearestSubway = subwayWithDist.slice(0, 5).map(s => ({
    name: s.n,
    routes: s.r.map((id, i) => ({ id, color: s.c[i] ?? '#888888' })),
    miles: toMiles(s.d),
  }))

  const cellLat = Math.floor(lat * 100)
  const cellLng = Math.floor(lng * 100)
  const nearbyBusAll = []
  for (let dLat = -1; dLat <= 1; dLat++) {
    for (let dLng = -1; dLng <= 1; dLng++) {
      const cell = `${cellLat + dLat},${cellLng + dLng}`
      for (const stop of busGrid[cell] ?? []) {
        nearbyBusAll.push({ ...stop, d: distMetres(lat, lng, stop.lat, stop.lng) })
      }
    }
  }
  nearbyBusAll.sort((a, b) => a.d - b.d)
  const seenRouteKeys = new Set()
  const nearestBus = []
  for (const stop of nearbyBusAll) {
    const key = stop.r.slice().sort().join(',')
    if (seenRouteKeys.has(key)) continue
    seenRouteKeys.add(key)
    nearestBus.push({ name: stop.n, routes: stop.r, miles: toMiles(stop.d) })
    if (nearestBus.length >= 5) break
  }

  // --- Schools (top 5) ---
  const schools = nearest5(loadSchools(), lat, lng).map(s => ({
    name: s.n, level: s.level, miles: toMiles(s._d), lat: s.lat, lng: s.lng,
  }))

  // --- Parks (top 5) ---
  const parks = nearest5(loadParks(), lat, lng).map(p => ({
    name: p.n, miles: toMiles(p._d), lat: p.lat, lng: p.lng,
  }))

  // --- Museums (top 5) ---
  const museums = nearest5(loadMuseums(), lat, lng).map(m => ({
    name: m.n, miles: toMiles(m._d), lat: m.lat, lng: m.lng,
  }))

  // --- Everyday: libraries + hospitals (top 5 total, closest first) ---
  const everyday = nearest5(loadEveryday(), lat, lng).map(e => ({
    name: e.n, kind: e.kind, miles: toMiles(e._d), lat: e.lat, lng: e.lng,
  }))

  return { subway: nearestSubway, bus: nearestBus, schools, parks, museums, everyday }
}

// ---------------------------------------------------------------------------
// Geocoding — NYC GeoSearch (Pelias, planninglabs.nyc)
// Called only when HC provides no lat/lng for a building.
// Accepts confident matches in the same borough; rejects "fallback" matches.
// ---------------------------------------------------------------------------

const GEOSEARCH_URL = 'https://geosearch.planninglabs.nyc/v2/search'

/** Map HC borough codes / names → GeoSearch borough names. */
const BOROUGH_MAP = {
  MN: 'Manhattan', BK: 'Brooklyn', QN: 'Queens', BX: 'Bronx', SI: 'Staten Island',
  MANHATTAN: 'Manhattan', BROOKLYN: 'Brooklyn', QUEENS: 'Queens', BRONX: 'Bronx',
  'STATEN ISLAND': 'Staten Island',
}

/**
 * Geocode a building address using NYC GeoSearch.
 * Returns {lat, lng} only when the result is a confident match in the same
 * borough. Returns null on network error, no results, or borough mismatch.
 */
async function geocodeAddress(address, city, borough) {
  try {
    const query = [address, city, 'NY'].filter(Boolean).join(', ')
    const url = `${GEOSEARCH_URL}?text=${encodeURIComponent(query)}&size=1`
    const res = await fetch(url, {
      headers: { 'User-Agent': UA },
      signal: AbortSignal.timeout(5000),
    })
    if (!res.ok) return null
    const data = await res.json()

    const feature = data.features?.[0]
    if (!feature) return null

    const [lng, lat] = feature.geometry?.coordinates ?? []
    if (typeof lat !== 'number' || typeof lng !== 'number') return null

    // NYC bounding box sanity check
    if (lat < 40.4 || lat > 40.95 || lng < -74.3 || lng > -73.65) return null

    // Reject "fallback" matches — too coarse
    if (feature.properties?.match_type === 'fallback') return null

    // Borough check: must match the listing's borough (when known)
    const expectedBorough = BOROUGH_MAP[borough?.toUpperCase?.() ?? ''] ?? null
    if (expectedBorough) {
      const featureBorough = feature.properties?.borough
      if (featureBorough && featureBorough.toLowerCase() !== expectedBorough.toLowerCase()) return null
    }

    return { lat, lng }
  } catch {
    return null
  }
}

const HC_API = 'https://a806-housingconnectapi.nyc.gov/HPDPublicAPI/api/Lottery/'
const CONTACT_URL = 'https://github.com/INBARSOL/lotto-lane-relay'
const UA = `LottoLane/1.0 (${CONTACT_URL})`

const SEARCH_PAYLOAD = JSON.stringify({
  UnitTypes: [], NearbyPlaces: [], NearbySubways: [], Amenities: [],
  Applied: null, HPDUserId: null, Boroughs: [], Neighborhoods: [],
  HouseholdSize: null, Income: '', HouseholdType: 1,
  OwnerTypes: [], PreferanceTypes: [], LotteryTypes: [],
  Min: null, Max: null, RentalSubsidy: null,
})

function log(msg) {
  console.log(`[relay] ${new Date().toISOString()} ${msg}`)
}

async function fetchSearch() {
  log('fetching SearchLotteries...')
  const res = await fetch(`${HC_API}SearchLotteries`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      'User-Agent': UA,
      Origin: 'https://housingconnect.nyc.gov',
      Referer: 'https://housingconnect.nyc.gov/',
    },
    body: SEARCH_PAYLOAD,
  })
  if (!res.ok) {
    const body = await res.text().catch(() => '')
    throw new Error(`SearchLotteries failed: HTTP ${res.status} — ${body.slice(0, 300)}`)
  }
  const data = await res.json()
  const count = (data.rentals?.length ?? 0) + (data.sales?.length ?? 0)
  log(`SearchLotteries ok — ${count} listings`)
  return data
}

async function fetchDetail(lotteryId) {
  const res = await fetch(`${HC_API}GetLotteryAdvertisement?lotteryId=${lotteryId}`, {
    headers: { 'User-Agent': UA, Accept: 'application/json' },
  })
  if (!res.ok) throw new Error(`GetLotteryAdvertisement?lotteryId=${lotteryId} failed: HTTP ${res.status}`)
  return res.json()
}

async function postListing(searchListingRaw, detailData, nearby) {
  const res = await fetch(`${WORKER_URL}/internal/ingest/listing`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Api-Secret': API_SECRET,
      'User-Agent': UA,
    },
    body: JSON.stringify({ searchListingRaw, detailData, nearby }),
  })
  if (!res.ok) {
    const body = await res.text().catch(() => '')
    throw new Error(`/ingest/listing failed: HTTP ${res.status} — ${body.slice(0, 300)}`)
  }
  return res.json()
}

/**
 * Validate photo URLs with HEAD requests. Returns urls that return HTTP 200
 * with an image/* content-type. Silently drops failures.
 * Also accumulates global photo stats for the owner alert in /ingest/complete.
 */
async function validatePhotoUrls(urls) {
  const valid = []
  for (const url of urls) {
    try {
      const res = await fetch(url, {
        method: 'HEAD',
        headers: { 'User-Agent': UA },
        signal: AbortSignal.timeout(5000),
      })
      const ct = res.headers.get('content-type') ?? ''
      if (res.ok && ct.startsWith('image/')) {
        valid.push(url)
      } else {
        log(`WARNING: photo HEAD failed ${url} — HTTP ${res.status} content-type=${ct}`)
        globalPhotoStats.failed++
      }
    } catch (err) {
      log(`WARNING: photo HEAD error ${url}: ${err.message}`)
      globalPhotoStats.failed++
    }
    globalPhotoStats.validated++
  }
  return valid
}

const globalPhotoStats = { validated: 0, failed: 0 }

async function postComplete(total, errorCount, prevCount, observedIds, photoStats) {
  const res = await fetch(`${WORKER_URL}/internal/ingest/complete`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Api-Secret': API_SECRET,
      'User-Agent': UA,
    },
    body: JSON.stringify({ total, errorCount, prevCount, observedIds, photoStats }),
  })
  if (!res.ok) {
    const body = await res.text().catch(() => '')
    throw new Error(`/ingest/complete failed: HTTP ${res.status} — ${body.slice(0, 300)}`)
  }
  return res.json()
}

async function main() {
  if (!DRY_RUN) {
    if (!WORKER_URL) throw new Error('WORKER_URL is required')
    if (!API_SECRET) throw new Error('API_SECRET is required')
  }

  // 1. Fetch search
  const searchResponse = await fetchSearch()
  const listings = [...(searchResponse.rentals ?? []), ...(searchResponse.sales ?? [])]

  if (listings.length === 0) {
    log('WARNING: zero listings returned — skipping ingest')
    process.exit(1)
  }

  // 2. Get prevCount before any writes (for drop check in /ingest/complete)
  let prevCount = 0
  if (!DRY_RUN) {
    // We ask the Worker for the current published count via /health (doesn't expose count)
    // so we pass prevCount=0 and let the Worker use its own countPublishedLotteries call.
    // The Worker's /ingest/complete does the count internally — prevCount here is just for
    // the Worker's reference; we pass the total listing count instead.
    prevCount = listings.length  // approximation; Worker queries D1 for the real prevCount
  }

  // 3. POST each listing individually — one Worker invocation per listing
  let errorCount = 0
  let nearbyCount = 0
  const statuses = {}
  // All IDs observed in this run (regardless of per-listing errors) — used for ghost detection.
  const observedIds = listings.map(l => String(l.lotteryId ?? l.LotteryId)).filter(Boolean)

  if (DRY_RUN) {
    log(`DRY_RUN=1 — would POST ${listings.length} listings to ${WORKER_URL ?? '(WORKER_URL not set)'}`)

    // Still fetch details so we can verify HC connectivity
    for (const listing of listings) {
      const id = listing.lotteryId ?? listing.LotteryId
      if (!id) continue
      try {
        await fetchDetail(id)
        await new Promise(r => setTimeout(r, 200))
      } catch (err) {
        log(`WARNING: detail fetch failed for ${id}: ${err.message}`)
        errorCount++
      }
    }
    log(`details: ${listings.length - errorCount} ok, ${errorCount} failed`)
    log('DRY_RUN complete — no Worker POSTs sent')
    process.exit(0)
  }

  for (const listing of listings) {
    const id = listing.lotteryId ?? listing.LotteryId
    if (!id) {
      errorCount++
      continue
    }

    let detailData
    try {
      detailData = await fetchDetail(id)
      await new Promise(r => setTimeout(r, 200))
    } catch (err) {
      log(`WARNING: detail fetch failed for ${id}: ${err.message}`)
      errorCount++
      continue
    }

    // Validate photo URLs from the detail response before POSTing.
    if (Array.isArray(detailData.photos)) {
      const rawUrls = detailData.photos.map(p => p.item1).filter(Boolean)
      const validUrls = await validatePhotoUrls(rawUrls)
      detailData = { ...detailData, photos: detailData.photos.filter(p => validUrls.includes(p.item1)) }
    }

    // Compute nearby transit/parks here (GitHub Actions has no CPU limit).
    // HC detail API nests lat/lng inside lotteryBuildings[0], not at the top level.
    const building = Array.isArray(detailData.lotteryBuildings) ? detailData.lotteryBuildings[0] : null
    let lat = building?.latitude ?? building?.Latitude ?? detailData.latitude ?? detailData.Latitude ?? null
    let lng = building?.longitude ?? building?.Longitude ?? detailData.longitude ?? detailData.Longitude ?? null

    // If HC provided no coordinates, geocode via NYC GeoSearch.
    if ((lat == null || lng == null) && building?.address) {
      const coords = await geocodeAddress(building.address, building.city, listing.borough)
      if (coords) {
        lat = String(coords.lat)
        lng = String(coords.lng)
        log(`geocoded listing ${id}: ${building.address} → ${coords.lat},${coords.lng}`)
      }
    }

    const nearby = computeNearby(
      lat != null ? parseFloat(lat) : null,
      lng != null ? parseFloat(lng) : null,
    )
    if (nearby) nearbyCount++

    try {
      const { result } = await postListing(listing, detailData, nearby)
      statuses[result.status] = (statuses[result.status] ?? 0) + 1
      if (result.status === 'error') {
        log(`WARNING listing ${id}: ${result.error}`)
        errorCount++
      }
    } catch (err) {
      log(`WARNING: failed to post listing ${id}: ${err.message}`)
      errorCount++
    }
  }

  log(`nearby computed for ${nearbyCount} of ${listings.length} listings`)
  log(`listings done — ${JSON.stringify(statuses)}, errors: ${errorCount}`)

  // 4. Signal completion — Worker does drop check, ghost reconcile, logs watchdog event, pings healthcheck
  const completeResult = await postComplete(listings.length, errorCount, prevCount, observedIds, globalPhotoStats)
  log(`complete: ${JSON.stringify(completeResult)}`)

  if (errorCount > 0) {
    log(`WARNING: ${errorCount} errors — Worker will ping /fail`)
    process.exitCode = 1
  }
}

main().catch(err => {
  console.error(`[relay] FATAL: ${err.message}`)
  process.exit(1)
})
