/**
 * Validate photo URLs with HEAD requests. Returns urls that return HTTP 200
 * with an image/* content-type. Silently drops failures.
 * Also accumulates global photo stats for the owner alert in /ingest/complete.
 */
async function validatePhotoUrls(urls) {
  const valid = []
  for (const url of urls) {
    try {
      const res = await fetch(url, {
        method: 'HEAD',
        headers: { 'User-Agent': UA },
        signal: AbortSignal.timeout(5000),
      })
      const ct = res.headers.get('content-type') ?? ''
      if (res.ok && ct.startsWith('image/')) {
        valid.push(url)
      } else {
        log(`WARNING: photo HEAD failed ${url} — HTTP ${res.status} content-type=${ct}`)
        globalPhotoStats.failed++
      }
    } catch (err) {
      log(`WARNING: photo HEAD error ${url}: ${err.message}`)
      globalPhotoStats.failed++
    }
    globalPhotoStats.validated++
  }
  return valid
}

const globalPhotoStats = { validated: 0, failed: 0, deduped: 0 }

// ---------------------------------------------------------------------------
// Persistent photo-hash cache
// ---------------------------------------------------------------------------

/** Max photo downloads per relay run. URLs beyond the cap are kept as-is. */
export const DOWNLOAD_CAP = 50
/** Drop cache entries older than this many days. */
const CACHE_MAX_AGE_DAYS = 30

/**
 * Path to the JSON cache file.  Set PHOTO_HASH_CACHE_PATH in the environment
 * (or pass explicitly to load/save) to override.  In GitHub Actions the
 * actions/cache step restores this file before the relay runs and saves it
 * after, so it persists across runs.
 */
export const PHOTO_HASH_CACHE_FILE =
  process.env.PHOTO_HASH_CACHE_PATH ?? join(__dirname, 'photo-hashes.json')

/**
 * In-memory store for the current run.
 * Each entry: { hash: '<hex>' | 'failed', date: 'YYYY-MM-DD' }
 *   hash='failed'  — last download attempt failed; retry allowed next day
 *   hash=<hex>     — SHA-256 of the image bytes; skip download on cache hit
 */
export const _photoHashCache = new Map() // url → { hash, date }

/** How many real photo downloads have been made this run. */
export let _downloadsThisRun = 0

/** Reset per-run counters (used by tests). */
export function _resetRunCounters() {
  _downloadsThisRun = 0
}

/**
 * Load the persistent cache from disk.  Prunes entries older than
 * CACHE_MAX_AGE_DAYS and populates _photoHashCache.
 */
export function loadPhotoHashCache(filePath = PHOTO_HASH_CACHE_FILE) {
  try {
    const raw = JSON.parse(readFileSync(filePath, 'utf-8'))
    const cutoff = new Date()
    cutoff.setDate(cutoff.getDate() - CACHE_MAX_AGE_DAYS)
    const cutoffStr = cutoff.toISOString().slice(0, 10)
    let loaded = 0, pruned = 0
    for (const [url, entry] of Object.entries(raw)) {
      if (typeof entry?.date !== 'string' || entry.date < cutoffStr) {
        pruned++
        continue
      }
      _photoHashCache.set(url, entry)
      loaded++
    }
    log(`photo-hash cache: loaded ${loaded}, pruned ${pruned} (>${CACHE_MAX_AGE_DAYS} days old)`)
  } catch (err) {
    if (err.code !== 'ENOENT') {
      log(`WARNING: could not read photo-hash cache (${err.message}) — starting fresh`)
    }
  }
}

/**
 * Persist _photoHashCache back to disk so the next run can reuse it.
 * Called at the end of main(); the actions/cache step then archives the file.
 */
export function savePhotoHashCache(filePath = PHOTO_HASH_CACHE_FILE) {
  const obj = {}
  for (const [url, entry] of _photoHashCache) obj[url] = entry
  try {
    writeFileSync(filePath, JSON.stringify(obj, null, 2), 'utf-8')
    log(`photo-hash cache: saved ${_photoHashCache.size} entries → ${filePath}`)
  } catch (err) {
    log(`WARNING: could not save photo-hash cache: ${err.message}`)
  }
}

/**
 * Deduplicate photos by content hash (SHA-256 of the downloaded bytes).
 *
 * Cache behaviour:
 *   - Cache hit (valid hash): skip download, use stored hash for dedup
 *   - Cache hit ('failed', same day): skip retry, keep URL as-is
 *   - Cache hit ('failed', earlier day): retry once; update entry
 *   - Not cached: download, hash, store
 *
 * Download cap: at most DOWNLOAD_CAP real GETs per relay run.  URLs beyond
 * the cap are kept as-is — no duplicate check is possible without the bytes,
 * so they carry through unchanged.  They will be checked on a future run once
 * the cache is warm.
 *
 * Always safe: a failed download keeps the URL in the result list.
 */
export async function deduplicateByContentHash(urls) {
  const today = new Date().toISOString().slice(0, 10)
  const seen = new Map() // hash → first url (within this call, for dedup)
  const result = []
  let cacheHits = 0, downloads = 0, failures = 0, capped = 0

  for (const url of urls) {
    const cached = _photoHashCache.get(url)

    if (cached) {
      if (cached.hash === 'failed') {
        if (cached.date === today) {
          // Already failed today — keep URL, count as cache hit
          result.push(url)
          cacheHits++
          continue
        }
        // Failed on a prior day — fall through to retry
      } else {
        // Valid cached hash — no download needed
        cacheHits++
        if (seen.has(cached.hash)) {
          log(`INFO: duplicate photo removed (same content as ${seen.get(cached.hash)}): ${url}`)
          globalPhotoStats.deduped++
          continue
        }
        seen.set(cached.hash, url)
        result.push(url)
        continue
      }
    }

    // Need to download — check the per-run cap first
    if (_downloadsThisRun >= DOWNLOAD_CAP) {
      result.push(url)
      capped++
      continue
    }

    _downloadsThisRun++
    downloads++
    try {
      const res = await fetch(url, {
        headers: { 'User-Agent': UA },
        signal: AbortSignal.timeout(10_000),
      })
      if (!res.ok) {
        _photoHashCache.set(url, { hash: 'failed', date: today })
        result.push(url)
        failures++
        continue
      }
      const buf = Buffer.from(await res.arrayBuffer())
      const hash = createHash('sha256').update(buf).digest('hex')
      _photoHashCache.set(url, { hash, date: today })
      if (seen.has(hash)) {
        log(`INFO: duplicate photo removed (same content as ${seen.get(hash)}): ${url}`)
        globalPhotoStats.deduped++
        continue
      }
      seen.set(hash, url)
      result.push(url)
    } catch (err) {
      log(`WARNING: photo hash-check failed for ${url}: ${err.message} — keeping it`)
      _photoHashCache.set(url, { hash: 'failed', date: today })
      result.push(url)
      failures++
    }
  }

  log(`photo dedup: checked=${urls.length} cache_hits=${cacheHits} downloads=${downloads} failures=${failures} deduped=${globalPhotoStats.deduped} capped=${capped}`)
  return result
}

async function postComplete(total, errorCount, prevCount, observedIds, photoStats) {
  const res = await fetch(`${WORKER_URL}/internal/ingest/complete`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Api-Secret': API_SECRET,
      'User-Agent': UA,
    },
    body: JSON.stringify({ total, errorCount, prevCount, observedIds, photoStats }),
  })
  if (!res.ok) {
    const body = await res.text().catch(() => '')
    throw new Error(`/ingest/complete failed: HTTP ${res.status} — ${body.slice(0, 300)}`)
  }
  return res.json()
}

async function main() {
  if (!DRY_RUN) {
    if (!WORKER_URL) throw new Error('WORKER_URL is required')
    if (!API_SECRET) throw new Error('API_SECRET is required')
  }

  // Load the persistent photo-hash cache (populated by actions/cache in GHA).
  loadPhotoHashCache()

  // 1. Fetch search
  const searchResponse = await fetchSearch()
  const listings = [...(searchResponse.rentals ?? []), ...(searchResponse.sales ?? [])]

  if (listings.length === 0) {
    console.error('[relay] FATAL: zero listings returned from Housing Connect — aborting ingest (no withdrawals made)')
    process.exit(1)
  }

  // Pre-ingest drop check: if the new count is <50% of the stored count, something
  // is wrong with HC (partial outage, WAF block, API change). Fail without ingesting
  // so ghost-reconciliation never runs and existing listings are preserved.
  if (!DRY_RUN) {
    const prevCount = await fetchPrevCount()
    if (prevCount >= 10 && listings.length < prevCount / 2) {
      console.error(
        `[relay] FATAL: listing count dropped from ${prevCount} to ${listings.length} (>${Math.round((1 - listings.length / prevCount) * 100)}% drop) — aborting ingest (no withdrawals made)`,
      )
      process.exit(1)
    }
    if (prevCount >= 10) {
      log(`pre-ingest count check ok — prev=${prevCount} now=${listings.length}`)
    }
  }

  // 2. POST each listing individually — one Worker invocation per listing
  let errorCount = 0
  let nearbyCount = 0
  const statuses = {}
  // All IDs observed in this run (regardless of per-listing errors) — used for ghost detection.
  const observedIds = listings.map(l => String(l.lotteryId ?? l.LotteryId)).filter(Boolean)

  if (DRY_RUN) {
    log(`DRY_RUN=1 — would POST ${listings.length} listings to ${WORKER_URL ?? '(WORKER_URL not set)'}`)

    // Still fetch details so we can verify HC connectivity
    for (const listing of listings) {
      const id = listing.lotteryId ?? listing.LotteryId
      if (!id) continue
      try {
        await fetchDetail(id)
        await new Promise(r => setTimeout(r, 200))
      } catch (err) {
        log(`WARNING: detail fetch failed for ${id}: ${err.message}`)
        errorCount++
      }
    }
    log(`details: ${listings.length - errorCount} ok, ${errorCount} failed`)
    log('DRY_RUN complete — no Worker POSTs sent')
    process.exit(0)
  }

  for (const listing of listings) {
    const id = listing.lotteryId ?? listing.LotteryId
    if (!id) {
      errorCount++
      continue
    }

    let detailData
    try {
      detailData = await fetchDetail(id)
      await new Promise(r => setTimeout(r, 200))
    } catch (err) {
      log(`WARNING: detail fetch failed for ${id}: ${err.message}`)
      errorCount++
      continue
    }

    // Validate photo URLs from the detail response before POSTing.
    if (Array.isArray(detailData.photos)) {
      const rawUrls = detailData.photos.map(p => p.item1).filter(Boolean)
      const validUrls = await validatePhotoUrls(rawUrls)
      // Remove photos that failed HEAD validation.
      let validPhotos = detailData.photos.filter(p => validUrls.includes(p.item1))
      // Deduplicate by content hash — catches same image served under different URLs.
      const validPhotoUrls = validPhotos.map(p => p.item1)
      const dedupedUrls = new Set(await deduplicateByContentHash(validPhotoUrls))
      validPhotos = validPhotos.filter(p => dedupedUrls.has(p.item1))
      detailData = { ...detailData, photos: validPhotos }
    }

    // Compute nearby transit/parks here (GitHub Actions has no CPU limit).
    // HC detail API nests lat/lng inside lotteryBuildings[0], not at the top level.
    const building = Array.isArray(detailData.lotteryBuildings) ? detailData.lotteryBuildings[0] : null
    let lat = building?.latitude ?? building?.Latitude ?? detailData.latitude ?? detailData.Latitude ?? null
    let lng = building?.longitude ?? building?.Longitude ?? detailData.longitude ?? detailData.Longitude ?? null

    // If HC provided no coordinates, geocode via NYC GeoSearch.
    if ((lat == null || lng == null) && building?.address) {
      const coords = await geocodeAddress(building.address, building.city, listing.borough)
      if (coords) {
        lat = String(coords.lat)
        lng = String(coords.lng)
        log(`geocoded listing ${id}: ${building.address} → ${coords.lat},${coords.lng}`)
      }
    }

    const nearby = computeNearby(
      lat != null ? parseFloat(lat) : null,
      lng != null ? parseFloat(lng) : null,
    )
    if (nearby) nearbyCount++

    try {
      const { result } = await postListing(listing, detailData, nearby)
      statuses[result.status] = (statuses[result.status] ?? 0) + 1
      if (result.status === 'error') {
        log(`WARNING listing ${id}: ${result.error}`)
        errorCount++
      }
    } catch (err) {
      log(`WARNING: failed to post listing ${id}: ${err.message}`)
      errorCount++
    }
  }

  log(`nearby computed for ${nearbyCount} of ${listings.length} listings`)
  log(`listings done — ${JSON.stringify(statuses)}, errors: ${errorCount}`)

  // 4. Persist photo-hash cache so next run can skip already-seen photos.
  savePhotoHashCache()

  // 5. Signal completion — Worker does drop check, ghost reconcile, logs watchdog event, pings healthcheck
  const completeResult = await postComplete(listings.length, errorCount, listings.length, observedIds, globalPhotoStats)
  log(`complete: ${JSON.stringify(completeResult)}`)

  if (errorCount > 0) {
    log(`WARNING: ${errorCount} errors — Worker will ping /fail`)
    process.exitCode = 1
  }
}

